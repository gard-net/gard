using System.Text;

namespace Gard.Cli;

/// <summary>
/// Scripts de completion generados desde <see cref="CliSpec"/>, así nunca se
/// desalinean de lo que el CLI acepta. Homebrew los instala vía
/// <c>generate_completions_from_executable</c>.
/// </summary>
public static class CompletionsCommand
{
    public static readonly string[] Shells = ["bash", "zsh", "fish", "powershell"];

    /// <summary>Valores cerrados de opciones, para completar después del flag.</summary>
    public static readonly IReadOnlyDictionary<string, string[]> Choices = new Dictionary<string, string[]>
    {
        ["--direction"] = ["up", "down", "bidir"],
        ["--transport"] = ["tcp", "udp"],
        ["--format"] = ["human", "json", "csv"],
        ["--bidir-mode"] = ["simultaneous", "sequential"],
        ["--style"] = ["rich", "plain"],
    };

    public static int Run(string[] args, CliContext ctx)
    {
        var shell = args.FirstOrDefault(a => !a.StartsWith('-'));
        if (shell is null || !Shells.Contains(shell))
            throw new CliOptionException($"choose a shell: {string.Join(", ", Shells)}");
        ctx.Out.Write(Generate(shell));
        return GardApp.Ok;
    }

    public static string Generate(string shell) => shell switch
    {
        "bash" => Bash(),
        "zsh" => Zsh(),
        "fish" => Fish(),
        "powershell" => PowerShell(),
        _ => throw new CliOptionException($"unsupported shell: {shell}"),
    };

    private static IEnumerable<string> Flags(IEnumerable<CliOptionSpec> options) =>
        options.SelectMany(o => o.Short is null ? [o.Name] : new[] { o.Name, o.Short });

    private static string CommandNames => string.Join(' ', CliSpec.Commands.Select(c => c.Name).Append("help"));

    private static string Bash()
    {
        var sb = new StringBuilder();
        sb.AppendLine("# bash completion for gard (generated by `gard completions bash`)");
        sb.AppendLine("_gard() {");
        sb.AppendLine("  local cur prev cmd opts");
        sb.AppendLine("  cur=\"${COMP_WORDS[COMP_CWORD]}\"");
        sb.AppendLine("  prev=\"${COMP_WORDS[COMP_CWORD-1]}\"");
        sb.AppendLine("  cmd=\"${COMP_WORDS[1]}\"");
        sb.AppendLine("  if [[ $COMP_CWORD -eq 1 ]]; then");
        sb.AppendLine($"    COMPREPLY=($(compgen -W \"{CommandNames} --help --version\" -- \"$cur\"))");
        sb.AppendLine("    return");
        sb.AppendLine("  fi");
        sb.AppendLine("  case \"$prev\" in");
        foreach (var (opt, values) in Choices)
            sb.AppendLine($"    {opt}) COMPREPLY=($(compgen -W \"{string.Join(' ', values)}\" -- \"$cur\")); return ;;");
        sb.AppendLine("  esac");
        sb.AppendLine("  case \"$cmd\" in");
        foreach (var c in CliSpec.Commands)
        {
            var words = c.Name == "completions" ? string.Join(' ', Shells) : string.Join(' ', Flags(c.Options));
            sb.AppendLine($"    {c.Name}) opts=\"{words}\" ;;");
        }
        sb.AppendLine($"    help) opts=\"{string.Join(' ', CliSpec.Commands.Select(c => c.Name))}\" ;;");
        sb.AppendLine("    *) opts=\"\" ;;");
        sb.AppendLine("  esac");
        sb.AppendLine($"  COMPREPLY=($(compgen -W \"$opts {string.Join(' ', Flags(CliSpec.GlobalOptions))}\" -- \"$cur\"))");
        sb.AppendLine("}");
        sb.AppendLine("complete -F _gard gard");
        return sb.ToString();
    }

    private static string Zsh()
    {
        var sb = new StringBuilder();
        sb.AppendLine("#compdef gard");
        sb.AppendLine("# zsh completion for gard (generated by `gard completions zsh`)");
        sb.AppendLine("_gard() {");
        sb.AppendLine("  local -a commands");
        sb.AppendLine("  commands=(");
        foreach (var c in CliSpec.Commands) sb.AppendLine($"    '{c.Name}:{ZshText(c.Summary)}'");
        sb.AppendLine("    'help:Show help for a command.'");
        sb.AppendLine("  )");
        sb.AppendLine("  if (( CURRENT == 2 )); then");
        sb.AppendLine("    _describe 'command' commands");
        sb.AppendLine("    return");
        sb.AppendLine("  fi");
        sb.AppendLine("  case $words[2] in");
        foreach (var c in CliSpec.Commands)
        {
            sb.AppendLine($"    {c.Name})");
            sb.Append("      _arguments");
            foreach (var o in c.Options.Concat(CliSpec.GlobalOptions)) sb.Append(" \\\n        " + ZshArg(o));
            if (c.Name == "completions") sb.Append($" \\\n        '1:shell:({string.Join(' ', Shells)})'");
            else if (c.MaxPositionals > 0) sb.Append(" \\\n        '1:host:_hosts'");
            sb.AppendLine();
            sb.AppendLine("      ;;");
        }
        sb.AppendLine($"    help) _values 'command' {string.Join(' ', CliSpec.Commands.Select(c => c.Name))} ;;");
        sb.AppendLine("  esac");
        sb.AppendLine("}");
        sb.AppendLine("_gard \"$@\"");
        return sb.ToString();
    }

    // '(-t --duration)'{-t,--duration}'[help]:S:' — formas excluyentes entre sí.
    private static string ZshArg(CliOptionSpec o)
    {
        var help = $"[{ZshText(o.Help)}]";
        var value = !o.TakesValue ? ""
            : Choices.TryGetValue(o.Name, out var values) ? $":{o.Value}:({string.Join(' ', values)})"
            : $":{o.Value}:";
        return o.Short is null
            ? $"'{o.Name}{help}{value}'"
            : $"'({o.Short} {o.Name})'{{{o.Short},{o.Name}}}'{help}{value}'";
    }

    private static string ZshText(string s) =>
        s.Replace("'", "'\\''").Replace("[", "(").Replace("]", ")").Replace(":", "\\:");

    private static string Fish()
    {
        var sb = new StringBuilder();
        sb.AppendLine("# fish completion for gard (generated by `gard completions fish`)");
        sb.AppendLine("complete -c gard -f");
        foreach (var c in CliSpec.Commands)
            sb.AppendLine($"complete -c gard -n __fish_use_subcommand -a {c.Name} -d '{FishText(c.Summary)}'");
        sb.AppendLine("complete -c gard -n __fish_use_subcommand -a help -d 'Show help for a command.'");
        foreach (var c in CliSpec.Commands)
        {
            var cond = $"'__fish_seen_subcommand_from {c.Name}'";
            foreach (var o in c.Options.Concat(CliSpec.GlobalOptions))
            {
                var line = new StringBuilder($"complete -c gard -n {cond} -l {o.Name[2..]}");
                if (o.Short is { } sh) line.Append($" -s {sh[1..]}");
                if (o.TakesValue)
                {
                    line.Append(" -r");
                    if (Choices.TryGetValue(o.Name, out var values)) line.Append($" -a '{string.Join(' ', values)}'");
                }
                line.Append($" -d '{FishText(o.Help)}'");
                sb.AppendLine(line.ToString());
            }
            if (c.Name == "completions")
                sb.AppendLine($"complete -c gard -n {cond} -a '{string.Join(' ', Shells)}'");
        }
        return sb.ToString();
    }

    private static string FishText(string s) => s.Replace("\\", "\\\\").Replace("'", "\\'");

    private static string PowerShell()
    {
        var sb = new StringBuilder();
        sb.AppendLine("# PowerShell completion for gard (generated by `gard completions powershell`)");
        sb.AppendLine("Register-ArgumentCompleter -Native -CommandName gard -ScriptBlock {");
        sb.AppendLine("    param($wordToComplete, $commandAst, $cursorPosition)");
        sb.AppendLine("    $words = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })");
        sb.AppendLine("    $commands = @{");
        foreach (var c in CliSpec.Commands)
        {
            var items = c.Name == "completions" ? Shells : Flags(c.Options);
            sb.AppendLine($"        '{c.Name}' = @({string.Join(", ", items.Select(i => $"'{i}'"))})");
        }
        sb.AppendLine("    }");
        sb.AppendLine("    $choices = @{");
        foreach (var (opt, values) in Choices)
            sb.AppendLine($"        '{opt}' = @({string.Join(", ", values.Select(v => $"'{v}'"))})");
        sb.AppendLine("    }");
        sb.AppendLine($"    $global = @({string.Join(", ", Flags(CliSpec.GlobalOptions).Select(f => $"'{f}'"))})");
        sb.AppendLine("    $prev = if ($words.Count -ge 2) { $words[$words.Count - 1] } else { '' }");
        sb.AppendLine("    if ($wordToComplete -ne '' -and $words.Count -ge 1) { $prev = if ($words.Count -ge 2) { $words[$words.Count - 2] } else { '' } }");
        sb.AppendLine("    if ($choices.ContainsKey($prev)) { $candidates = $choices[$prev] }");
        sb.AppendLine("    elseif ($words.Count -le 1 -or ($words.Count -eq 2 -and $wordToComplete -ne '')) { $candidates = @($commands.Keys) + 'help' }");
        sb.AppendLine("    elseif ($commands.ContainsKey($words[1])) { $candidates = $commands[$words[1]] + $global }");
        sb.AppendLine("    else { $candidates = $global }");
        sb.AppendLine("    $candidates | Where-Object { $_ -like \"$wordToComplete*\" } | ForEach-Object {");
        sb.AppendLine("        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }
}
